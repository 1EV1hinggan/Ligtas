const { validate } = require("./lib/validate");
const assert = require("assert");
const ok = (b) => { const r = validate(b); assert(!r.error, JSON.stringify(r)); return r; };
const bad = (b, why) => { const r = validate(b); assert(r.error, "should reject: " + why); };
const d = { title: "FIRE", body: "Evacuate", incoming_alert_id: "a1", type: "ALERT", sent_at: "1", by: "X" };
ok({ target: "/topics/ligtas_campus", data: d, ttl: 1800 });
ok({ target: "condition:'campus_a' in topics && 'bld_x' in topics", data: d, ttl: 1800 });
ok({ target: "condition:'teach_bsit_2' in topics || 'teachp_bsit' in topics", data: d, ttl: 1800 });
assert.strictEqual(ok({ target: "/topics/a", data: d, ttl: 999999 }).ttl, 7200);
assert.strictEqual(ok({ target: "/topics/a", data: d }).ttl, 60);
bad({ target: "fcm-token-abc123:APA91b", data: d }, "single token");
bad({ target: "/topics/a b", data: d }, "space in topic");
bad({ target: "condition:'a' in topics; drop", data: d }, "semicolon");
bad({ target: "/topics/a", data: { ...d, evil: "1" } }, "unknown key");
bad({ target: "/topics/a", data: { ...d, type: "NUKE" } }, "bad type");
bad({ target: "/topics/a", data: { ...d, body: "x".repeat(601) } }, "long body");
bad({ target: "/topics/a", data: { title: "t" } }, "no alert id");
assert.strictEqual(ok({ target: "/topics/a", data: { ...d, title_tl: "SUNOG ALERT", body_tl: "May sunog." } }).data.title_tl, "SUNOG ALERT");
bad({ target: "/topics/a", data: { ...d, body_tl: "x".repeat(601) } }, "long taglish body");
bad(null, "null"); bad({}, "empty");
console.log("validation tests: all passed");
